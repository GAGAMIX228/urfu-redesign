/* Умный поиск: понимает разговорные слова и синонимы, прощает опечатки.
   SmartSearch.terms(запрос, текст_всего_индекса) → список основ слов для поиска;
   SmartSearch.norm(текст) → текст в нижнем регистре, «ё» как «е». */
(function () {
  function norm(t) { return String(t || '').toLowerCase().replace(/ё/g, 'е'); }
  function words(t) { return norm(t).split(/[^a-zа-я0-9]+/).filter(Boolean); }
  function stem(w) { return w.length <= 4 ? w : w.slice(0, Math.min(5, w.length)); }

  /* разговорные слова и синонимы → что искать */
  var SYN = {
    'общага': 'общежитие', 'общаги': 'общежитие', 'общагу': 'общежитие', 'общаге': 'общежитие', 'жилье': 'общежитие', 'поселиться': 'общежитие заселение',
    'стипа': 'стипендия', 'стипуха': 'стипендия', 'стипендуха': 'стипендия',
    'пары': 'расписание', 'пар': 'расписание', 'занятия': 'расписание', 'уроки': 'расписание',
    'айти': 'программная информатика информационная', 'ит': 'программная информатика информационная', 'it': 'программная информатика информационная', 'прога': 'программная', 'программист': 'программная', 'программирование': 'программная',
    'ии': 'искусственный интеллект', 'ai': 'искусственный интеллект', 'нейросети': 'искусственный интеллект', 'нейросеть': 'искусственный интеллект',
    'кибер': 'безопасность', 'кибербезопасность': 'информационная безопасность', 'хакер': 'безопасность', 'нейронки': 'искусственный интеллект',
    'бесплатно': 'бюджет', 'платно': 'стоимость договор', 'контракт': 'стоимость договор', 'цена': 'стоимость',
    'лк': 'личный кабинет', 'кабинет': 'личный кабинет',
    'универ': 'университет', 'вуз': 'университет', 'урфу': 'университет',
    'абитура': 'поступление', 'абитуриент': 'поступление', 'поступить': 'поступление', 'поступать': 'поступление',
    'баллы': 'проходные баллы', 'проходной': 'проходные баллы', 'егэ': 'егэ баллы',
    'карта': 'карта кампуса адрес', 'адрес': 'адрес карта', 'где': 'карта адрес',
    'физра': 'спорт', 'физкультура': 'спорт', 'качалка': 'спорт', 'бассейн': 'спорт плавания',
    'клуб': 'клубы', 'кружок': 'клубы', 'секция': 'клубы спорт',
    'мероприятия': 'события', 'ивенты': 'события', 'олимпиады': 'олимпиада',
    'препод': 'преподаватель', 'преподы': 'преподаватель', 'учитель': 'преподаватель',
    'деканат': 'институт', 'факультет': 'институт', 'ртф': 'ирит ртф',
    'телефон': 'контакты телефон', 'позвонить': 'контакты телефон', 'почта': 'контакты'
  };

  function lev(a, b, max) {
    if (Math.abs(a.length - b.length) > max) return max + 1;
    var prev = [], cur, i, j;
    for (j = 0; j <= b.length; j++) prev[j] = j;
    for (i = 1; i <= a.length; i++) {
      cur = [i]; var best = i;
      for (j = 1; j <= b.length; j++) {
        cur[j] = Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
        if (cur[j] < best) best = cur[j];
      }
      if (best > max) return max + 1;
      prev = cur;
    }
    return prev[b.length];
  }

  var vocabCache = { key: '', list: [] };
  function vocab(corpus) {
    if (vocabCache.key === corpus) return vocabCache.list;
    var seen = {}, list = [];
    words(corpus).forEach(function (w) { if (w.length >= 4 && !seen[w]) { seen[w] = 1; list.push(w); } });
    vocabCache = { key: corpus, list: list };
    return list;
  }

  /* основы слов запроса: синонимы + исправление опечаток по словам, которые есть на сайте */
  function terms(q, corpus) {
    var out = [], nc = norm(corpus);
    words(q).forEach(function (w) {
      if (SYN[w]) { words(SYN[w]).forEach(function (x) { if (x.length >= 2) out.push(stem(x)); }); return; }
      if (w.length < 2 || (w.length < 3 && !/^[a-z0-9]+$/.test(w))) return;
      var st = stem(w);
      if (nc.indexOf(st) !== -1 || w.length < 5) { out.push(st); return; }
      /* слова нет на сайте — ищем похожее (1 ошибка в коротком слове, 2 — в длинном) */
      var max = w.length >= 8 ? 2 : 1, best = null, bd = max + 1;
      vocab(corpus).forEach(function (v) {
        var d = lev(w, v.slice(0, w.length + 1), max);
        if (d < bd) { bd = d; best = v; }
      });
      out.push(best ? stem(best) : st);
    });
    var uniq = [];
    out.forEach(function (x) { if (uniq.indexOf(x) === -1) uniq.push(x); });
    return uniq;
  }
  window.SmartSearch = { terms: terms, norm: norm };
})();
